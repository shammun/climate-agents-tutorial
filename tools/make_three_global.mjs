// Converts three.module.min.js into a classic script that defines window.THREE.
// Browsers refuse to load ES module files from file://, but classic scripts load fine.
// Usage: node tools/make_three_global.mjs <output.js> [<output2.js> ...]
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../node_modules/three/', import.meta.url);
const src = readFileSync(new URL('build/three.module.min.js', root), 'utf8');
const version = JSON.parse(readFileSync(new URL('package.json', root), 'utf8')).version;

if (/^\s*import[\s{*]/m.test(src) || src.includes('import.meta')) {
  throw new Error('three.module.min.js has imports; cannot convert to a global build');
}
const m = src.match(/export\s*\{([^}]*)\};?\s*$/);
if (!m) throw new Error('export list not found at end of three.module.min.js');

const props = m[1].split(',').map(s => {
  const [local, exported] = s.trim().split(/\s+as\s+/);
  return `${exported ?? local}:${local}`;
});
const body = src.slice(0, m.index);
const out = `/* three.js r${version} global build (generated by tools/make_three_global.mjs) */\n` +
  `(function(){${body}\nwindow.THREE=Object.freeze({${props.join(',')}});})();\n`;

const targets = process.argv.slice(2);
if (!targets.length) throw new Error('give at least one output path');
for (const t of targets) { writeFileSync(t, out); console.log('wrote', t, (out.length / 1024).toFixed(0), 'KB'); }
